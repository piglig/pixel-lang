"""Freeze Unicode general categories for native execution; no runtime Python dependency."""
import argparse
from pathlib import Path
import unicodedata

UNICODE_VERSION = '15.1.0'
TARGET = Path(__file__).resolve().parents[1] / 'pixellang/native_unicode.h'
REFERENCE = TARGET.with_name('unicode_data.py')


def generate():
    if unicodedata.unidata_version != UNICODE_VERSION:
        raise SystemExit(f'Requires Unicode {UNICODE_VERSION}; found {unicodedata.unidata_version}')
    ranges = []
    prior = None
    identifier_ranges = []
    previous_flags = None
    for point in range(0x110000):
        character = chr(point)
        category = unicodedata.category(character)
        flags = int(character.isidentifier()) | (int(("a"+character).isidentifier()) << 1)
        if flags != previous_flags:
            identifier_ranges.append((point,flags))
            previous_flags = flags
        if category != prior:
            ranges.append((point, category))
            prior = category
    names = sorted({category for _, category in ranges})
    lines = [f'/* Generated by scripts/generate_native_unicode.py from CPython unicodedata, UCD {UNICODE_VERSION}. */',
             f'#define PIXEL_UNICODE_VERSION "{UNICODE_VERSION}"',
             'static const uint32_t pixel_category_text[][2] = {']
    lines += ['    {' + ','.join(str(ord(ch)) for ch in name) + '},' for name in names]
    lines += ['};', 'static PixelString pixel_category_names[] = {']
    lines += [f'    {{SIZE_MAX,2,pixel_category_text[{i}]}},' for i in range(len(names))]
    lines += ['};', 'static const struct { uint32_t start; unsigned char category; } pixel_category_ranges[] = {']
    lines += [f'    {{0x{point:06x},{names.index(category)}}},' for point, category in ranges]
    lines += ['};', '''static PixelValue pixel_unicode_category(PixelContext *c, PixelValue text) {
    pixel_check_type(c,text,PIXEL_STRING);
    if (text.string->length!=1 || text.string->data[0]>0x10ffff)
        pixel_fail(c,"Expected one Unicode scalar");
    uint32_t point=text.string->data[0];
    size_t low=0,high=sizeof(pixel_category_ranges)/sizeof(pixel_category_ranges[0]);
    while (low<high) {
        size_t middle=low+(high-low)/2;
        if (pixel_category_ranges[middle].start<=point) low=middle+1;
        else high=middle;
    }
    return (PixelValue){.kind=PIXEL_STRING,.string=&pixel_category_names[pixel_category_ranges[low-1].category]};
}''']
    lines += ['static const struct { uint32_t start; unsigned char flags; } pixel_identifier_ranges[] = {']
    lines += [f'    {{0x{point:06x},{flags}}},' for point,flags in identifier_ranges]
    lines += ['};', """static int pixel_identifier(PixelString *text) {
    if (!text->length) return 0;
    for (size_t i=0; i<text->length; i++) {
        uint32_t point=text->data[i];
        if (point>0x10ffff) return 0;
        size_t low=0,high=sizeof(pixel_identifier_ranges)/sizeof(pixel_identifier_ranges[0]);
        while (low<high) {
            size_t middle=low+(high-low)/2;
            if (pixel_identifier_ranges[middle].start<=point) low=middle+1;
            else high=middle;
        }
        if (!(pixel_identifier_ranges[low-1].flags & (i ? 2 : 1))) return 0;
    }
    return 1;
}"""]
    reference = [f'"""Generated Unicode {UNICODE_VERSION} general categories; see generate_native_unicode.py."""',
                 'from bisect import bisect_right', f'UNICODE_VERSION = {UNICODE_VERSION!r}',
                 f'CATEGORIES = {tuple(names)!r}', 'STARTS = (']
    reference += [f'    0x{point:06x},' for point, _ in ranges]
    reference += [')', 'CATEGORY_IDS = bytes([']
    for offset in range(0,len(ranges),32):
        reference.append('    '+','.join(str(names.index(category)) for _,category in ranges[offset:offset+32])+',')
    reference += ['])', '', 'def category(character):',
                  '    if not isinstance(character,str) or len(character)!=1:',
                  '        raise ValueError("Expected one Unicode scalar")',
                  '    return CATEGORIES[CATEGORY_IDS[bisect_right(STARTS,ord(character))-1]]', '']
    return '\n'.join(lines) + '\n', '\n'.join(reference)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source, reference = generate()
    if args.check:
        if TARGET.read_text() != source or REFERENCE.read_text() != reference:
            raise SystemExit('Native Unicode table is stale')
    else:
        TARGET.write_text(source)
        REFERENCE.write_text(reference)
