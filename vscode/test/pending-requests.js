const assert = require('node:assert/strict');
const {PendingRequests, waitFor} = require('../src/pending-requests');
(async () => {
  const requests = new PendingRequests();
  let calls = 0, finish;
  const operation = () => { calls++; return new Promise(resolve => { finish = resolve; }); };
  const first = requests.run('project', operation);
  const controller = new AbortController();
  const cancelled = waitFor(first, controller.signal);
  const second = requests.run('project', operation);
  assert.equal(first, second);
  controller.abort();
  await assert.rejects(cancelled, {name:'AbortError'});
  finish({files:{'main.pxl':'fn main(){}'}});
  assert((await second).files);
  assert.equal(calls, 1);
  await requests.run('project', () => { calls++; return 'fresh'; });
  assert.equal(calls, 2);
  await assert.rejects(requests.run('project', () => { throw new Error('read failed'); }), /read failed/);
  assert.equal(await requests.run('project', () => 'retry'), 'retry');
  let releaseOld, releaseNew;
  const old = requests.run('project', () => new Promise(resolve => {releaseOld=resolve;}));
  await Promise.resolve();
  requests.clear();
  const next = requests.run('project', () => new Promise(resolve => {releaseNew=resolve;}));
  await Promise.resolve();
  releaseOld('old'); await old;
  assert.equal(requests.run('project', () => 'incorrect'), next);
  releaseNew('new'); assert.equal(await next, 'new');
  console.log('In-flight workspace reads coalesce; cancellation is per consumer; failures and completed reads are not cached.');
})().catch(error => { console.error(error); process.exitCode = 1; });
